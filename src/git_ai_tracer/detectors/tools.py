"""Signatures and detectors for AI coding tools and assistants."""

import re
from typing import Dict, List, Optional
from git_ai_tracer.models import Evidence, EvidenceType, ToolCategory, ToolDetection


class ToolRule:
    def __init__(
        self,
        name: str,
        category: ToolCategory = ToolCategory.CODING_ASSISTANT,
        file_patterns: Optional[List[str]] = None,
        file_regexes: Optional[List[str]] = None,
        commit_regexes: Optional[List[str]] = None,
        confidence: float = 0.95,
    ):
        self.name = name
        self.category = category
        self.file_patterns = file_patterns or []
        self.file_regexes = [re.compile(r, re.IGNORECASE) for r in (file_regexes or [])]
        self.commit_regexes = [re.compile(r, re.IGNORECASE) for r in (commit_regexes or [])]
        self.confidence = confidence

    def check_files(self, paths: List[str]) -> List[Evidence]:
        evidences = []
        for path in paths:
            norm_path = path.strip().lstrip("/")
            # Exact or suffix match
            for pat in self.file_patterns:
                if norm_path == pat or norm_path.endswith(f"/{pat}") or norm_path.startswith(f"{pat}/") or f"/{pat}/" in norm_path:
                    evidences.append(
                        Evidence(
                            type=EvidenceType.CONFIG if ("rule" in pat or "config" in pat or pat.endswith(".md")) else EvidenceType.FILE,
                            match=path,
                            confidence=self.confidence,
                            details=f"Matched configuration marker: {pat}",
                        )
                    )
                    break
            # Regex match
            for regex in self.file_regexes:
                if regex.search(norm_path):
                    evidences.append(
                        Evidence(
                            type=EvidenceType.CONFIG,
                            match=path,
                            confidence=self.confidence,
                            details=f"Matched path pattern regex: {regex.pattern}",
                        )
                    )
                    break
        return evidences

    def check_commits(self, commit_messages: List[str]) -> List[Evidence]:
        evidences = []
        for msg in commit_messages:
            for regex in self.commit_regexes:
                if regex.search(msg):
                    # Truncate first line for neatness
                    first_line = msg.split("\n", 1)[0].strip()
                    evidences.append(
                        Evidence(
                            type=EvidenceType.COMMIT,
                            match=first_line[:80],
                            confidence=self.confidence,
                            details=f"Matched commit signature: {regex.pattern}",
                        )
                    )
                    break
        return evidences


