IGNORED_PATH_PREFIXES = (
    "node_modules/",
    "vendor/",
    ".venv/",
    "venv/",
    "site-packages/",
    "Pods/",
    "dist/",
    "build/",
    "target/",
)


def detect_tools(
    file_paths: List[str],
    commit_messages: Optional[List[str]] = None,
) -> List[ToolDetection]:
    """Scan file paths and commit history to detect AI coding tools used."""
    results: List[ToolDetection] = []
    commits = commit_messages or []

    # Filter out vendored/dependency paths to prevent false positives
    clean_paths = [
        p for p in file_paths
        if not any(p.startswith(pref) or f"/{pref}" in p for pref in IGNORED_PATH_PREFIXES)
    ]

    for rule in TOOL_RULES:
        evidences: List[Evidence] = []
        # Check paths
        evidences.extend(rule.check_files(clean_paths))
        # Check commits
        evidences.extend(rule.check_commits(commits))

        if evidences:
            # Aggregate confidence
            max_conf = max(e.confidence for e in evidences)
            # Remove duplicate matches
            unique_evidence = []
            seen = set()
            for ev in evidences:
                key = (ev.type, ev.match)
                if key not in seen:
                    seen.add(key)
                    unique_evidence.append(ev)

            results.append(
                ToolDetection(
                    tool_name=rule.name,
                    category=rule.category,
                    confidence=round(max_conf, 2),
                    evidence=unique_evidence,
                )
            )

    return sorted(results, key=lambda x: x.confidence, reverse=True)
